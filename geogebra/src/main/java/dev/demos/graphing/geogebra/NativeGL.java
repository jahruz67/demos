package dev.demos.graphing.geogebra;

import java.nio.Buffer;

/** GLES 2 calls shared by Android's GLES20 and desktop's native JOGL context. */
public interface NativeGL {
    int GL_VERTEX_SHADER=0x8B31, GL_FRAGMENT_SHADER=0x8B30, GL_COMPILE_STATUS=0x8B81;
    int GL_ARRAY_BUFFER=0x8892, GL_ELEMENT_ARRAY_BUFFER=0x8893, GL_STREAM_DRAW=0x88E0;
    int GL_FLOAT=0x1406, GL_UNSIGNED_SHORT=0x1403, GL_UNSIGNED_BYTE=0x1401;
    int GL_TRIANGLES=4, GL_TRIANGLE_STRIP=5, GL_LINE_LOOP=2, GL_LINE_STRIP=3;
    int GL_FRONT=0x0404, GL_BACK=0x0405, GL_EQUAL=0x0202, GL_LEQUAL=0x0203;
    int GL_BLEND=0x0BE2, GL_CULL_FACE=0x0B44, GL_DEPTH_TEST=0x0B71, GL_POLYGON_OFFSET_FILL=0x8037;
    int GL_COLOR_BUFFER_BIT=0x4000, GL_DEPTH_BUFFER_BIT=0x0100;
    int GL_SRC_ALPHA=0x0302, GL_ONE_MINUS_SRC_ALPHA=0x0303;
    int GL_TEXTURE_2D=0x0DE1, GL_RGBA=0x1908, GL_ALPHA=0x1906;
    int GL_TEXTURE_MAG_FILTER=0x2800, GL_TEXTURE_MIN_FILTER=0x2801, GL_NEAREST=0x2600, GL_LINEAR=0x2601;
    int GL_TEXTURE_WRAP_S=0x2802, GL_TEXTURE_WRAP_T=0x2803, GL_CLAMP_TO_EDGE=0x812F;
    int GL_FRAMEBUFFER=0x8D40, GL_RENDERBUFFER=0x8D41, GL_DEPTH_COMPONENT16=0x81A5;
    int GL_COLOR_ATTACHMENT0=0x8CE0, GL_DEPTH_ATTACHMENT=0x8D00, GL_FRAMEBUFFER_COMPLETE=0x8CD5;
    int compileShader(int type, String source);
    void checkProgram(int program);
    int glCreateProgram();
    void glAttachShader(int program,int shader);
    void glBindAttribLocation(int program,int index,String name);
    void glLinkProgram(int program);
    int glGetUniformLocation(int program,String name);
    void glGenBuffers(int count,int[] buffers,int offset);
    void glBindBuffer(int target,int buffer);
    void glVertexAttribPointer(int index,int size,int type,boolean normalized,int stride,int offset);
    void glUniform3fv(int location,int count,float[] values,int offset);
    void glUniform3f(int location,float x,float y,float z);
    void glEnableVertexAttribArray(int index);
    void glBufferData(int target,int size,Buffer data,int usage);
    void glDrawElements(int mode,int count,int type,int offset);
    void glUniformMatrix4fv(int location,int count,boolean transpose,float[] values,int offset);
    void glUseProgram(int program);
    void glDisableVertexAttribArray(int index);
    void glDetachShader(int program,int shader);
    void glDeleteShader(int shader);
    void glDeleteProgram(int program);
    void glUniform4f(int location,float a,float b,float c,float d);
    void glUniform4fv(int location,int count,float[] values,int offset);
    void glUniform2fv(int location,int count,float[] values,int offset);
    void glViewport(int x,int y,int width,int height);
    void glUniform1i(int location,int value);
    void glUniform1fv(int location,int count,float[] values,int offset);
    void glCullFace(int mode);
    void glStencilFunc(int func,int ref,int mask);
    void glDepthMask(boolean flag);
    void glColorMask(boolean r,boolean g,boolean b,boolean a);
    void glClearColor(float r,float g,float b,float a);
    void glPolygonOffset(float factor,float units);
    void glGenTextures(int count,int[] textures,int offset);
    void glBindTexture(int target,int texture);
    void glEnable(int capability);
    void glDisable(int capability);
    void glClear(int mask);
    void glBindFramebuffer(int target,int framebuffer);
    void glBindRenderbuffer(int target,int renderbuffer);
    void glTexParameterf(int target,int name,float value);
    void glTexImage2D(int target,int level,int internalFormat,int width,int height,int border,int format,int type,Buffer data);
    void glRenderbufferStorage(int target,int format,int width,int height);
    void glGenRenderbuffers(int count,int[] buffers,int offset);
    void glGenFramebuffers(int count,int[] buffers,int offset);
    void glFramebufferTexture2D(int target,int attachment,int textarget,int texture,int level);
    void glFramebufferRenderbuffer(int target,int attachment,int rendertarget,int renderbuffer);
    int glCheckFramebufferStatus(int target);
    void glDepthFunc(int func);
    void glBlendFunc(int source,int destination);
    void glGenerateMipmap(int target);
    void glDeleteTextures(int count,int[] textures,int offset);
    void glDeleteBuffers(int count,int[] buffers,int offset);
}
